# “负数索引是列表逆序” ❌
# 不够精确。负数索引只是从末尾倒数定位单个字符，跟“逆序”不是一回事：
# s[-1] 是最后一个字符
# s[-2] 是倒数第二个
# 逆序是 s[::-1]，那是切片加步长 -1 干的事
# 两个概念别混。

# “左闭右开” 你意思对，但表述乱。精确说法：
# 切片 s[a:b] 包含索引 a，不包含索引 b。
# 换成数学：a ≤ 索引 < b。
# 你写的“大于等于”“小于”方向对，但“列表左边可以取到”这种说法以后别用，直接说“包含起始，不包含结束”。

# \t 和 \\ 你标了不知道
# \t = 制表符，相当于按一次 Tab 键，常用来对齐。你写 print("a\tb\tc")，输出里三个字母之间会隔开一段空白。
# \\ = 一个反斜杠字符本身。因为 \ 在字符串里是转义符，想打印一个真的 \ 就得写 \\。比如 print("C:\\Users") 输出 C:\Users。


