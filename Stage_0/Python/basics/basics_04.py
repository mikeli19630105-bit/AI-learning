### 反馈笔记
# split() 返回的是列表不是字符串"a b c".split() 返回 ["a", "b", "c"]
# . join()方向对，但语法说反了   '分隔符'.join(可迭代对象)
# strip() 不只能去空格，也能去指定字符，比如 strip(".") 会去掉两端的点。
# replace(旧, 新) 把字符串里所有“旧”替换成“新”。
# 比如 "a-b-c".replace("-", "_") 返回 "a_b_c"，原来的 "a-b-c" 还在。
# 这一点很重要：字符串是不可变的，所有字符串方法都返回新字符串，不会改原来的。


